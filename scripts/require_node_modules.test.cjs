'use strict'

const assert = require('node:assert/strict')
const { mkdirSync, mkdtempSync, writeFileSync, existsSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { spawnSync } = require('node:child_process')
const { test } = require('node:test')

const SCRIPT = join(__dirname, 'require_node_modules.cjs')
const LOCK = {
  packages: {
    '': { name: 'root' },
    'node_modules/tool': { version: '1.0.0', dev: true },
    'node_modules/tool-linux-x64': { version: '1.0.0', dev: true, optional: true },
    'node_modules/workspace': { resolved: 'packages/workspace', link: true },
    'packages/workspace/node_modules/nested': { version: '2.0.0', dev: true },
  },
}

function project(installed) {
  const dir = mkdtempSync(join(tmpdir(), 'require-node-modules-'))
  writeFileSync(join(dir, 'package-lock.json'), JSON.stringify(LOCK))
  for (const [path, version] of Object.entries(installed)) {
    mkdirSync(join(dir, path), { recursive: true })
    writeFileSync(join(dir, path, 'package.json'), JSON.stringify({ version }))
  }
  return dir
}

function hook(dir, code = 0) {
  return spawnSync(
    process.execPath,
    [SCRIPT, process.execPath, '-e', `require('fs').writeFileSync('ran', ''); process.exit(${code})`],
    { cwd: dir, encoding: 'utf8' },
  )
}

test('refuses to run the hook without node_modules', () => {
  const dir = project({})
  const result = hook(dir)
  assert.equal(result.status, 1)
  assert.match(
    result.stderr,
    /Missing or at another version: node_modules\/tool, packages\/workspace\/node_modules\/nested\./,
  )
  assert.match(result.stderr, /Run `npm ci`/)
  assert.equal(existsSync(join(dir, 'ran')), false)
})

test('refuses to run the hook when a package is not at its locked version', () => {
  const dir = project({ 'node_modules/tool': '1.1.0', 'packages/workspace/node_modules/nested': '2.0.0' })
  const result = hook(dir)
  assert.equal(result.status, 1)
  assert.match(result.stderr, /Missing or at another version: node_modules\/tool\./)
  assert.equal(existsSync(join(dir, 'ran')), false)
})

test('runs the hook and returns its exit status when node_modules matches the lockfile', () => {
  const dir = project({ 'node_modules/tool': '1.0.0', 'packages/workspace/node_modules/nested': '2.0.0' })
  const result = hook(dir, 3)
  assert.equal(result.status, 3)
  assert.equal(result.stderr, '')
  assert.equal(existsSync(join(dir, 'ran')), true)
})
