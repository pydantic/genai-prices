'use strict'

// Runs a command only when node_modules holds every package at the version package-lock.json pins. The pre-commit JS
// hooks and `make build`'s prettier step run through it. Without that check, `npx prettier` runs the newest prettier
// from the registry, which rewrites files the pinned one leaves alone, and `npm run` falls back to whatever eslint or
// tsc is on PATH.
const { readFileSync } = require('node:fs')
const { spawnSync } = require('node:child_process')

function installedVersion(path) {
  try {
    return JSON.parse(readFileSync(`${path}/package.json`, 'utf8')).version
  } catch {
    return undefined
  }
}

const { packages } = JSON.parse(readFileSync('package-lock.json', 'utf8'))
const unpinned = Object.entries(packages).filter(
  ([path, { version, optional }]) =>
    path.includes('node_modules/') && version && !optional && installedVersion(path) !== version,
)
if (unpinned.length > 0) {
  const shown = unpinned.slice(0, 3).map(([path]) => path)
  const more = unpinned.length > shown.length ? ` and ${unpinned.length - shown.length} more` : ''
  console.error(
    `node_modules does not match package-lock.json. Missing or at another version: ${shown.join(', ')}${more}. ` +
      'Run `npm ci`, then try again.',
  )
  process.exit(1)
}

const [command, ...args] = process.argv.slice(2)
const { status, error } = spawnSync(command, args, { stdio: 'inherit' })
if (error) throw error
process.exit(status ?? 1)
